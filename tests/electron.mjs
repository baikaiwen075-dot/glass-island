import { _electron as electron } from 'playwright';
import { mkdtemp, readFile, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
const base = path.resolve('.');
const packaged = process.argv.includes('--packaged');
await mkdir('test-results', { recursive: true });
const dataDir = await mkdtemp(path.join(base, 'test-results/data-'));
const failures = [];
let app;
async function launch() {
  const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE;
  app = await electron.launch({ ...(packaged ? { executablePath: path.join(base, 'release/win-unpacked/Glass Island.exe') } : {}), args: [...(packaged ? [] : [base]), '--smoke-test', `--data-dir=${dataDir}`], env, timeout: 60000 });
  const page = await app.firstWindow();
  page.on('pageerror', error => failures.push(error.message));
  await page.locator('.preview-panel').first().waitFor();
  return page;
}
async function call(page, action, payload) {
  const reply = await page.evaluate(([action, payload]) => window.island.call(action, payload), [action, payload]);
  assert.equal(reply.ok, true, reply.error); return reply.value;
}
async function waitFor(page, predicate, args) { await page.waitForFunction(predicate, args, { timeout: 10000 }); }
try {
  const page = await launch();
  assert.equal(await page.locator('.preview-panel').count(), 4);
  await page.screenshot({ path: 'test-results/editor.png' });
  const initial = await call(page, 'get');
  const note = initial.panels.find(p => p.type === 'note');
  await page.locator(`[data-select="${note.id}"]`).click();
  await page.locator('#content-text').fill('持久化验证 <img src=x onerror="alert(1)">\n第二行');
  await waitFor(page, () => document.querySelector('.note-text').textContent.includes('持久化验证'));
  assert.equal(await page.locator('.note-text img').count(), 0);
  await page.locator('#field-opacity').evaluate(element => { element.value = '46'; });
  await page.locator('#field-opacity').dispatchEvent('input');
  await waitFor(page, id => document.querySelector(`[data-id="${id}"]`).style.getPropertyValue('--glass-opacity') === '0.46', note.id);
  await page.locator('[data-add="calendar"]').click();
  await waitFor(page, () => document.querySelectorAll('.preview-panel').length === 5);
  assert.equal(await page.locator('.calendar-grid').count(), 1);
  const calendarId = (await call(page, 'get')).panels.find(p => p.type === 'calendar').id;
  const beforeDrag = (await call(page, 'get')).panels.find(p => p.id === calendarId);
  const bounds = await page.locator(`[data-id="${calendarId}"]`).boundingBox();
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + 25);
  await page.mouse.down(); await page.mouse.move(bounds.x + bounds.width / 2 + 40, bounds.y + 55, { steps: 5 }); await page.mouse.up();
  await waitFor(page, () => !document.querySelector('#inspector').textContent.includes('undefined'));
  await page.waitForFunction(async ([id, before]) => { const s = (await window.island.call('get')).value; return s.panels.find(p => p.id === id).x > before; }, [calendarId, beforeDrag.x]);
  const handle = await page.locator(`[data-id="${calendarId}"] .resize-handle`).boundingBox();
  await page.mouse.move(handle.x + 5, handle.y + 5); await page.mouse.down(); await page.mouse.move(handle.x + 40, handle.y + 30, { steps: 4 }); await page.mouse.up();
  await page.waitForFunction(async ([id, before]) => (await window.island.call('get')).value.panels.find(p => p.id === id).width > before, [calendarId, beforeDrag.width]);
  await page.locator('[data-theme="dusk"]').click();
  await waitFor(page, () => document.querySelector('#canvas').classList.contains('dusk'));
  await page.locator('[data-theme="forest"]').click();
  await call(page, 'panel:update', { id: note.id, patch: { locked: true } });
  await page.locator('#desktop-button').click();
  await page.waitForFunction(async () => (await window.island.call('get')).value.desktopEnabled);
  const nativeWindows = await app.evaluate(async ({ BrowserWindow }) => {
    const windows = BrowserWindow.getAllWindows();
    await Promise.all(windows.map(w => w.webContents.isLoading() ? new Promise(resolve => w.webContents.once('did-finish-load', resolve)) : Promise.resolve()));
    return windows.filter(w => w.webContents.getURL().includes('widget.html')).map(w => ({ url: w.webContents.getURL(), resizable: w.isResizable() }));
  });
  assert.equal(nativeWindows.length, 5);
  assert.equal(nativeWindows.find(w => w.url.includes(note.id)).resizable, false);
  const widget = app.windows().find(p => p.url().includes(note.id));
  assert.ok(widget, 'native note window exists');
  widget.on('pageerror', error => failures.push(error.message));
  await widget.locator('.live-note').waitFor();
  await widget.locator('.live-note').fill('来自桌面面板的修改');
  await page.waitForFunction(async id => (await window.island.call('get')).value.panels.find(p => p.id === id).data.text === '来自桌面面板的修改', note.id);
  const denied = await widget.evaluate(() => window.island.call('panel:add', 'note'));
  assert.equal(denied.ok, false, 'widget cannot invoke editor-only operations');
  const crossPanel = await widget.evaluate(id => window.island.call('panel:update', { id, patch: { title: 'unauthorized' } }), calendarId);
  assert.equal(crossPanel.ok, false, 'widget cannot mutate another panel');
  await call(page, 'clickthrough:toggle');
  assert.ok((await call(page, 'get')).clickThrough);
  await call(page, 'clickthrough:toggle');
  const duplicate = await call(page, 'panel:duplicate', calendarId);
  assert.notEqual(duplicate, calendarId);
  await call(page, 'panel:update', { id: duplicate, patch: { visible: false } });
  const exportPath = path.join(dataDir, 'exported.json');
  await app.evaluate(({ dialog }, exportPath) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: exportPath }); }, exportPath);
  await call(page, 'layout:export');
  const exported = JSON.parse(await readFile(exportPath, 'utf8'));
  assert.equal(exported.panels.length, 6);
  const imported = { ...exported, panels: exported.panels.map(p => p.id === note.id ? { ...p, title: '导入后的便签' } : p) };
  const importPath = path.join(dataDir, 'imported.json'); await writeFile(importPath, JSON.stringify(imported));
  await app.evaluate(({ dialog }, importPath) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [importPath] }); dialog.showMessageBox = async () => ({ response: 1 }); }, importPath);
  await call(page, 'layout:import');
  assert.equal((await call(page, 'get')).panels.find(p => p.id === note.id).title, '导入后的便签');
  assert.equal(JSON.parse(await readFile(path.join(dataDir, 'before-import.json'), 'utf8')).panels.find(p => p.id === note.id).title, note.title);
  await app.evaluate(({ dialog }) => { dialog.showMessageBox = async () => ({ response: 0 }); });
  await call(page, 'panel:remove', duplicate);
  assert.ok((await call(page, 'get')).panels.some(p => p.id === duplicate), 'cancel keeps panel');
  await app.evaluate(({ dialog }) => { dialog.showMessageBox = async () => ({ response: 1 }); });
  await call(page, 'panel:remove', duplicate);
  assert.equal((await call(page, 'get')).panels.length, 5);
  await call(page, 'desktop:toggle');
  const saveExpected = await call(page, 'get');
  await app.close(); app = null;
  const disk = JSON.parse(await readFile(path.join(dataDir, 'layout.json'), 'utf8'));
  assert.equal(disk.panels.find(p => p.id === note.id).data.text, '来自桌面面板的修改');
  const restored = await launch();
  const restoredState = await call(restored, 'get');
  assert.equal(restoredState.panels.length, saveExpected.panels.length);
  assert.equal(restoredState.panels.find(p => p.id === note.id).title, '导入后的便签');
  await restored.setViewportSize({ width: 1080, height: 740 });
  await restored.screenshot({ path: 'test-results/editor-1080.png' });
  const overflow = await restored.evaluate(() => ({ w: document.documentElement.scrollWidth > innerWidth, h: document.documentElement.scrollHeight > innerHeight }));
  assert.equal(overflow.w, false); assert.equal(overflow.h, false);
  assert.deepEqual(failures, []);
  console.log('PASS: edit, text escaping, material, add, drag, resize, themes, native windows, locking, direct note editing, IPC permissions, click-through, duplicate, visibility, export/import backup, delete confirmation, save/relaunch, minimum window layout.');
} finally { if (app) await app.close(); }
